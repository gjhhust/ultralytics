#!/usr/bin/env python3
"""Create the small YAML bridge required by the historical YOLOFT loader.

The canonical XS-VID v2 JSON and generated YOLO labels remain the source data.
This script writes no annotations and introduces no links; it only writes a
portable data YAML whose absolute root is the supplied downloaded data root.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path


NAMES = (
    "bicycle-static",
    "bicycle-person",
    "car",
    "person",
    "ignore",
    "truck",
    "boat",
)


def write_legacy_split(root: Path, split_name: str) -> Path:
    """Write image-root-relative paths expected by the historical loader."""
    source = root / "splits" / f"{split_name}.txt"
    destination = root / "splits" / f"legacy_{split_name}.txt"
    image_root = (root / "images").resolve()
    lines = []

    for raw_line in source.read_text(encoding="utf-8").splitlines():
        raw_line = raw_line.strip()
        if not raw_line:
            continue
        image_path = Path(raw_line)
        if not image_path.is_absolute():
            image_path = source.parent / image_path
        image_path = Path(os.path.abspath(image_path))
        try:
            relative_path = image_path.relative_to(image_root)
        except ValueError as exc:
            raise ValueError(f"{source}: image is outside {image_root}: {raw_line}") from exc
        lines.append(f"./{relative_path.as_posix()}")

    if not lines:
        raise ValueError(f"{source}: split is empty")
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return destination


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data-root", type=Path, required=True, help="Downloaded XS-VID v2 root")
    parser.add_argument("--output", type=Path, default=None)
    parser.add_argument(
        "--detection-protocol",
        choices=("canonical", "paper"),
        default="paper",
        help="Use paper for reported-result reproduction; canonical for new benchmark results.",
    )
    args = parser.parse_args()

    root = args.data_root.resolve()
    required = (
        root / "images",
        root / "labels",
        root / "splits" / "train.txt",
        root / "splits" / "test.txt",
        root / "annotations" / "test.json",
    )
    missing = [str(path) for path in required if not path.exists()]
    if missing:
        raise FileNotFoundError("Missing release files:\n" + "\n".join(missing))

    if args.detection_protocol == "paper":
        evaluation_json = root / "annotations" / "protocols" / "paper_detection_test.json"
    else:
        evaluation_json = root / "annotations" / "test.json"
    if not evaluation_json.is_file():
        raise FileNotFoundError(evaluation_json)

    for split_name in ("train", "val_dev", "test"):
        write_legacy_split(root, split_name)

    output = args.output or root / "legacy_yoloft.yaml"
    output.parent.mkdir(parents=True, exist_ok=True)
    names = "".join(f"  {index}: {name}\n" for index, name in enumerate(NAMES))
    output.write_text(
        "# Generated by YOLOFT tools/xsvid/prepare_legacy_layout.py\n"
        f"path: {root}\n"
        "train: splits/legacy_train.txt\n"
        "val: splits/legacy_val_dev.txt\n"
        "test: splits/legacy_test.txt\n\n"
        "labels_dir: labels\n"
        "images_dir: images\n"
        "StreamVideoSampler: True\n"
        "train_video_length: [1]\n"
        "train_video_interval: 2\n\n"
        f"eval_ann_json: {evaluation_json}\n"
        "classes_map: [0, 1, 2, 3, 4, 5, 6]\n"
        "names:\n" + names,
        encoding="utf-8",
    )
    print(f"Wrote {output}")


if __name__ == "__main__":
    main()
